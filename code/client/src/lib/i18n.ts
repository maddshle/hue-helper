export type TranslationKey = keyof typeof messages.en;

export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (_match, name: string) => String(values[name] ?? `{${name}}`));
}

export function getInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem("hue-helper-language");
    if (saved === "id" || saved === "en") return saved;
  } catch {
    // The preference can still follow the browser language when storage is unavailable.
  }
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("id") ? "id" : "en";
}

