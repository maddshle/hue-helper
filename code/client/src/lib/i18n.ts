export function translateColorName(name: string, language: Language): string {
  if (language === "en") return name;
  return indonesianColorNames[normalizeColorName(name)] ?? name;
}

const historySources: Record<string, TranslationKey> = {
  "Camera scan": "cameraScanSource",
  "Photo sample": "photoSampleSource",
  "Photo center": "photoCenterSource",
  "Color catalog": "colorCatalogSource",
  "Color picker": "colorPickerSource",
  "Manual entry": "manualEntrySource",
};

export function translateHistorySource(source: string, language: Language): string {
  const key = historySources[source];
  return key ? translate(language, key) : source;
}
